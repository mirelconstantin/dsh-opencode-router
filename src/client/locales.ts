/**
 * The `zh` seat the host's locale contract requires.
 *
 * `ctx.locale.register` takes `Record<BuiltInLocaleId, ...>`, and the ids are
 * fixed to exactly `["zh", "en"]` — a plugin that omits `zh` will not
 * typecheck, let alone load. So the key has to exist; what it holds is a
 * choice. This plugin ships no translated copy: `zh` IS `en`, so there is one
 * set of strings to maintain and no second dictionary to drift out of sync
 * with it. A user whose UI preference is Chinese reads the same English text
 * as everyone else, which is the intent of an English-only project.
 */
export const zh = en
